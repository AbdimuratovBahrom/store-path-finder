# === Создание базы ===
if os.path.exists(DB_PATH):
    os.remove(DB_PATH)
    print("🗑️ Старая база удалена")

conn = sqlite3.connect(DB_PATH)
cursor = conn.cursor()

cursor.execute("""
CREATE TABLE IF NOT EXISTS shops (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    block TEXT,
    row TEXT,
    shop TEXT,
    path TEXT,
    is_specific INTEGER DEFAULT 0
)
""")

# === Функция добавления обычных блоков ===
def insert_block_from_func(block_name, func):
    data = func()
    if not data:
        print(f"⚠️ Нет данных для {block_name}")
        return
    for entry in data:
        path = entry.get("path")
        shops = entry.get("shops", [])
        row_name = None
        for part in path.split(">"):
            p = part.strip()
            if p.startswith("Ряд"):
                row_name = p.replace("Ряд", "").strip()
                break
        for s in shops:
            cursor.execute(
                "INSERT INTO shops (block, row, shop, path, is_specific) VALUES (?, ?, ?, ?, 0)",
                (block_name, row_name, s, path)
            )

# === Добавляем обычные блоки ===
insert_block_from_func("1-блок", get_block1_data)
insert_block_from_func("2-блок", get_block2_data)
insert_block_from_func("3-блок", get_block3_data)
insert_block_from_func("38-склад", get_block38_data)
insert_block_from_func("Гипермаркет", get_blockGiper_data)

# === Добавляем специфические объекты по блокам ===
for block, entries in SPECIFIC_OBJECTS.items():
    for entry in entries:
        path = entry["path"]
        shops = entry.get("shops", [])
        row_name = None
        for part in path.split(">"):
            p = part.strip()
            if p.startswith("Ряд"):
                row_name = p.replace("Ряд", "").strip()
                break
        if not row_name:
            row_name = "Спец"
        for s in shops:
            cursor.execute(
                "INSERT INTO shops (block, row, shop, path, is_specific) VALUES (?, ?, ?, ?, 1)",
                (block, row_name, s, path)
            )

# === Добавляем глобальные специфические объекты (вкладка) ===
cursor.executemany(
    "INSERT INTO shops (block, row, shop, path, is_specific) VALUES (?, ?, ?, ?, 1)",
    GLOBAL_SPECIFIC_OBJECTS
)

conn.commit()
conn.close()
print("✅ База успешно обновлена: все блоки + специфические объекты добавлены.")





